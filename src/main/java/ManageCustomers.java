        private void loadCustomers() {
      DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    try (Connection c = DBconnection.getConnection()) {

        if (c == null) {
            JOptionPane.showMessageDialog(this, "Database connection error");
            return;
        }

        String sql = "SELECT customer_id, customer_name, gender, phone, " +
                     "room_number, deposit, check_in, check_out, amount_pending " +
                     "FROM customers";
        PreparedStatement ps = c.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            int customerId       = rs.getInt("customer_id");
            String customerName  = rs.getString("customer_name");
            String gender        = rs.getString("gender");
            String phone         = rs.getString("phone");
            int roomNumber       = rs.getInt("room_number");
            double deposit       = rs.getDouble("deposit");
            Date checkIn         = rs.getDate("check_in");
            Date checkOut        = rs.getDate("check_out");
            double amountPending = rs.getDouble("amount_pending");

            model.addRow(new Object[] {
                customerId,
                customerName,
                gender,
                phone,
                roomNumber,
                deposit,
                checkIn,
                checkOut,
                amountPending
            });
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }

