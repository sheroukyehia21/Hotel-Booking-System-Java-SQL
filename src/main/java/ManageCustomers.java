    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed

    int row = jTable1.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a customer");
        return;
    }

    int customerId       = (int)    jTable1.getValueAt(row, 0);
    String customerName  = (String) jTable1.getValueAt(row, 1);
    int roomNumber       = (int)    jTable1.getValueAt(row, 4);
    double deposit       = (double) jTable1.getValueAt(row, 5);
    java.sql.Date checkInDate = (java.sql.Date) jTable1.getValueAt(row, 6);
    double amountPending = (double) jTable1.getValueAt(row, 8);

    double totalAmount = deposit + amountPending;

    new Checkout(customerId, customerName, roomNumber,
                 checkInDate, deposit, amountPending, totalAmount).setVisible(true);
    dispose();

    }//GEN-LAST:event_jButton5ActionPerformed

